"""US-style PDF statements print their period headings above the table, not inside it."""
from app.files import documents, routing

INCOME_PAGE = """Acme Inc.
CONDENSED CONSOLIDATED STATEMENTS OF OPERATIONS (Unaudited)
(In millions)
Three Months Ended Twelve Months Ended
September 26, September 27, September 26, September 27,
2026 2025 2026 2025
Net sales:
"""
BALANCE_PAGE = """Acme Inc.
CONDENSED CONSOLIDATED BALANCE SHEETS (Unaudited)
(In millions)
September 26, September 27,
2026 2025
ASSETS:
"""

INCOME_GRID = [
    ["Total net sales (1)", "$ 114,477", None, "102,466", None, "478,834", None, "416,161"],
    ["Total cost of sales", "59,657", None, "54,125", None, "245,232", None, "220,960"],
    ["Net income", "$ 30,711", None, "27,466", None, "$ 132,175", None, "$ 112,010"],
]
BALANCE_GRID = [
    ["Total assets", "$ 404,548", None, "$ 359,241"],
    ["Total liabilities", "292,455", None, "285,508"],
    ["Total shareholders equity", "112,093", None, "73,733"],
]


def test_reads_quarter_and_year_columns_from_page_text():
    cols = documents._pdf_column_periods(INCOME_PAGE)
    assert [(c["months"], c["label"]) for c in cols] == [
        (3, "3M to September 26, 2026"), (3, "3M to September 27, 2025"),
        (12, "September 26, 2026"), (12, "September 27, 2025")]


def test_balance_sheet_columns_are_dated_points_not_durations():
    cols = documents._pdf_column_periods(BALANCE_PAGE)
    assert [c["label"] for c in cols] == ["September 26, 2026", "September 27, 2025"]
    assert all(c["months"] is None for c in cols)


def test_quarter_and_year_columns_never_share_a_statement():
    sheets, note = documents._pdf_table_sheets("Page 1 · Table 1", INCOME_GRID, INCOME_PAGE, 1, 1)
    assert note is None and len(sheets) == 2
    stmts = routing.suggest_statements(sheets, "x.pdf")
    by_months = {len(s["periods"]): s for s in stmts}
    assert {s["sheet"].split("· ")[-1] for s in stmts} == {"12 months", "3 months"}
    year = next(s for s in stmts if s["sheet"].endswith("12 months"))
    assert year["periods"] == ["September 27, 2025", "September 26, 2026"]  # oldest first
    rev = next(line for line in year["lines"] if line["key"] == "revenue")
    assert rev["values"] == [416161.0, 478834.0]
    assert len(by_months) == 1  # both have two periods; neither mixes durations


def test_balance_sheet_lines_map_with_dates():
    sheets, _ = documents._pdf_table_sheets("Page 2 · Table 1", BALANCE_GRID, BALANCE_PAGE, 2, 1)
    (stmt,) = routing.suggest_statements(sheets, "x.pdf")
    assert stmt["statement"] == "balance"
    keys = {line["key"]: line["values"] for line in stmt["lines"]}
    assert keys["total_assets"] == [359241.0, 404548.0]
    assert keys["total_equity"] == [73733.0, 112093.0]


