def test_an_upload_analysed_by_an_older_parser_is_reanalysed_when_opened(client):
    """Uploads saved before a parser fix must pick the fix up without being uploaded again."""
    import io

    from openpyxl import Workbook
    from sqlalchemy.orm import Session

    from app.db.models import Upload
    from app.db.session import get_engine

    wb = Workbook()
    ws = wb.active
    ws.append(["Line item", "FY2024", "FY2025"])
    ws.append(["Total net sales", 100, 120])
    ws.append(["Total cost of sales", 60, 70])
    buf = io.BytesIO()
    wb.save(buf)
    r = client.post("/api/uploads", files=[("files", ("pl.xlsx", buf.getvalue()))])
    up = r.json()["results"][0]["upload"]
    assert up["analysis"]["parser_rev"] >= 3

    with Session(get_engine()) as db:  # make it look like an upload saved by the old code
        row = db.get(Upload, __import__("uuid").UUID(up["id"]))
        row.statements = []
        row.analysis = {k: v for k, v in row.analysis.items() if k != "parser_rev"}
        db.commit()

    got = client.get(f"/api/uploads/{up['id']}").json()
    keys = {line["key"] for s in got["statements"] for line in s["lines"]}
    assert {"revenue", "cogs"} <= keys
    assert got["analysis"]["parser_rev"] >= 3
